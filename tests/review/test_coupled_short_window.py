"""Budget-only short-window regressions; never instantiate/advance real physics.

The independent cost references below are literals from the original five-step
measurement, not outputs generated by affordable_choice. All existing runtime
and evidence files are read-only; temporary receipts are deliberately forged.
"""
from pathlib import Path
import ast
import contextlib
import copy
import inspect
import io
import json
import math
import sys
import tempfile
import types
import unittest
from unittest.mock import Mock, patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'scripts'))
import run_coupled_short_window as short

base = short.base


class CoupledShortWindowTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest, cls.cfg, cls.p, cls.resolved = short.original_cost()

    def bindings(self):
        """Mirror the separate-process binding, restoring it after each test."""
        stack = contextlib.ExitStack()
        stack.enter_context(patch.object(base, 'settings', short.short_settings))
        stack.enter_context(patch.object(base, 'SOURCES', short.ORIGINAL_SOURCES+short.EXTRA))
        stack.enter_context(patch.object(base, 'budget_report', short.short_budget_report))
        return stack

    def test_01_literal_original_cost_selects_700ns_and_not_800ns(self):
        result = short.affordable_choice(self.manifest, self.cfg)
        # Independent references: dt_min=1.0490418295392004e-8 s;
        # slowest step=3.9976580000002286 s, factor=1.5, overhead=30 s.
        self.assertAlmostEqual(result['end_time_s'], 7e-7, delta=1e-20)
        self.assertEqual(result['estimated_steps'], 67)
        self.assertAlmostEqual(result['forecast_wall_seconds'], 431.764629000023,
                               delta=1e-9)
        self.assertEqual(math.ceil(8e-7/1.0490418295392004e-8), 77)
        next_quantum_cost = 1.5*3.9976580000002286*77+30
        self.assertAlmostEqual(next_quantum_cost, 491.7294990000264, delta=1e-9)
        self.assertLessEqual(result['forecast_wall_seconds'], 450.)
        self.assertGreater(next_quantum_cost, 450.)
        self.assertEqual(self.cfg['forecast_multiplier'], 1.5)
        self.assertEqual(self.cfg['forecast_overhead_seconds'], 30.)
        self.assertEqual(self.cfg['forecast_launch_limit_seconds'], 450.)

    def test_02_only_horizon_changes_all_physical_values_and_old_files_identical(self):
        paths = [ROOT/name for name in short.ORIGINAL_SOURCES]+[short.PROBE]
        before = {str(path): base.sha(path) for path in paths}
        cfg, physical, resolved = short.short_settings()
        self.assertEqual(physical, self.p)
        self.assertEqual(base.fingerprint(physical), base.fingerprint(self.p))
        self.assertEqual(resolved['parameters'], self.resolved['parameters'])
        for key, value in self.cfg.items():
            if key != 'registered_end_times_s': self.assertEqual(cfg[key], value, key)
        self.assertEqual(self.cfg['registered_end_times_s'], [2e-6, 4e-6])
        self.assertEqual(resolved['original_explicit_configuration'], self.cfg)
        self.assertAlmostEqual(cfg['registered_end_times_s'][0], 7e-7, delta=1e-20)
        self.assertEqual(before, {str(path): base.sha(path) for path in paths})

    def test_03_receipt_declares_transfer_not_fabricated_new_cost_probe(self):
        report = short.short_budget_report(short.PROBE)
        self.assertEqual(report['evidence_status'],
            'TRANSFER_ORIGINAL_MEASURED_COST_SAME_PHYSICAL_PARAMETERS_NOT_A_NEW_PROBE')
        self.assertEqual(report['probe_manifest_sha256'], base.sha(short.PROBE))
        self.assertEqual(report['probe_manifest_path'],
                         'outputs/coupled_afsd_20261002/cost_probe/manifest.json')
        self.assertEqual(report['original_long_horizons_status'], 'NOT_RUN_COST_EXCEEDS_BUDGET')
        self.assertEqual(set(report['source_sha256']), set(short.ORIGINAL_SOURCES+short.EXTRA))
        self.assertNotEqual(report['configuration_sha256'], self.manifest['configuration_sha256'])
        self.assertFalse(report['production_authorized'])
        self.assertTrue(report['physical_parameters_unchanged'])
        self.assertEqual(report['internal_limit_s'], 540.)
        self.assertEqual(report['external_limit_s'], 570.)
        self.assertEqual(json.loads(short.PROBE.read_text(encoding='utf-8')), self.manifest)

    def test_04_source_configuration_and_artifact_drift_rejected(self):
        real_sha = base.sha
        source = (ROOT/short.ORIGINAL_SOURCES[0]).resolve()
        artifact = (short.PROBE.parent/next(iter(self.manifest['artifact_sha256']))).resolve()
        for target, expected in ((source, 'runtime source changed'),
                                 (artifact, 'cost artifact changed')):
            def altered(path, target=target):
                return 'WRONG' if Path(path).resolve() == target else real_sha(path)
            with self.subTest(target=str(target)), patch.object(base, 'sha', side_effect=altered):
                with self.assertRaisesRegex(ValueError, expected): short.original_cost()
        changed = copy.deepcopy(self.resolved)
        changed['parameters']['shear'] *= .99
        with patch.object(short, 'ORIGINAL_SETTINGS', return_value=(self.cfg, self.p, changed)):
            with self.assertRaisesRegex(ValueError, 'configuration changed'): short.original_cost()

    def test_05_selection_is_cost_only_and_unaffordable_quantum_is_not_run(self):
        changed = copy.deepcopy(self.manifest)
        changed['final_diagnostics'] = {'plastic_points': 999999, 'ep_max': 1000.,
                                        'expected_paper_match': True}
        self.assertEqual(short.affordable_choice(changed, self.cfg),
                         short.affordable_choice(self.manifest, self.cfg))
        changed['step_wall_seconds'] = [100.]*5
        with self.assertRaisesRegex(ValueError, 'NOT_RUN'):
            short.affordable_choice(changed, self.cfg)
        changed['accepted_dt_s'] = [0.]*5
        with self.assertRaisesRegex(ValueError, 'invalid cost'):
            short.affordable_choice(changed, self.cfg)

    def test_06_saved_original_settings_prevents_recursive_monkey_binding(self):
        original_run = base.run
        self.assertIsNot(short.ORIGINAL_SETTINGS, short.short_settings)
        with self.bindings():
            manifest, _, physical, _ = short.original_cost()
            cfg, rebound_p, _ = base.settings()
            report = base.budget_report(short.PROBE)
            self.assertEqual(manifest, self.manifest)
            self.assertEqual(physical, rebound_p)
            self.assertEqual(cfg['registered_end_times_s'], [report['choice']['end_time_s']])
            self.assertIs(base.run, original_run)
        self.assertIs(base.settings, short.ORIGINAL_SETTINGS)

    def test_07_entrypoint_delegates_same_original_run_and_solver_fresh_initial_state(self):
        source = ast.parse(inspect.getsource(base.run))
        imports = [(node.module, alias.name) for node in ast.walk(source)
                   if isinstance(node, ast.ImportFrom) for alias in node.names]
        self.assertIn(('afsd_backend.pysph.coupled_solver', 'IntegratedSolver'), imports)
        calls = [node for node in ast.walk(source) if isinstance(node, ast.Call)
                 and isinstance(node.func, ast.Name) and node.func.id == 'IntegratedSolver']
        self.assertEqual(len(calls), 1)
        self.assertIsInstance(calls[0].args[0], ast.Call)
        self.assertEqual(calls[0].args[0].func.id, 'initial_particles')
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)/'trial'; receipt = Path(directory)/'budget.json'
            with self.bindings(), patch.object(base, 'run', return_value=37) as run, \
                 patch.object(sys, 'argv', ['run_coupled_short_window.py', '--output', str(output),
                                           '--budget', str(receipt)]):
                self.assertEqual(short.main(), 37)
                run.assert_called_once_with(output, budget=receipt)
                self.assertIs(base.settings, short.short_settings)
                self.assertIs(base.budget_report, short.short_budget_report)
                self.assertEqual(base.SOURCES, short.ORIGINAL_SOURCES+short.EXTRA)

    def test_08_forged_choice_or_source_receipt_rejected_before_solver_instantiation(self):
        constructor = Mock(side_effect=AssertionError('no physical run permitted in this test'))
        stub = types.ModuleType('afsd_backend.pysph.coupled_solver')
        stub.IntegratedSolver = constructor
        original = short.short_budget_report(short.PROBE)
        for attack in ('choice', 'source'):
            receipt = copy.deepcopy(original)
            if attack == 'choice': receipt['choice']['end_time_s'] = 2e-6
            else: receipt['source_sha256'][short.EXTRA[0]] = 'WRONG'
            with self.subTest(attack=attack), tempfile.TemporaryDirectory() as directory:
                path = Path(directory)/'receipt.json'
                path.write_text(json.dumps(receipt), encoding='utf-8')
                with self.bindings(), patch.dict(sys.modules, {'afsd_backend.pysph.coupled_solver': stub}):
                    with self.assertRaisesRegex(ValueError, 'recomputed cost evidence'):
                        base.run(Path(directory)/'trial', budget=path)
                self.assertFalse((Path(directory)/'trial').exists())
        constructor.assert_not_called()

    def test_09_no_alternative_probe_evidence_is_accepted(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)/'fake_probe.json'
            path.write_text(json.dumps(self.manifest), encoding='utf-8')
            with self.assertRaisesRegex(ValueError, 'only registered cost evidence'):
                short.short_budget_report(path)

    def test_10_budget_generation_does_not_overwrite_prior_evidence(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)/'budget.json'
            path.write_text('ORIGINAL_EVIDENCE', encoding='utf-8')
            with patch.object(sys, 'argv', ['run_coupled_short_window.py', '--output', str(path),
                                           '--select-budget']), contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(FileExistsError, 'fresh short budget'):
                    short.main()
            self.assertEqual(path.read_text(encoding='utf-8'), 'ORIGINAL_EVIDENCE')


if __name__ == '__main__': unittest.main(verbosity=2)
