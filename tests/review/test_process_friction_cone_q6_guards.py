"""Q6 acceptance/Jacobian guards, independent of the contact root reference."""
from pathlib import Path
import sys
import unittest
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'scripts'))
from probe_process_friction_cone import ConeBlock, cone_response, cone_rows, feasible_cone
from probe_process_plastic import CandidateFailure


def snapshot(b):
    return [b.displacement.copy(), b.stress.copy(), b.pa.S.copy(), b.pa.ep.copy(),
        b.pa.x.copy(), b.pa.y.copy(), b.pa.z.copy(), b.friction.copy(),
        b.contact_force.copy(), b.tangent_force.copy(), b.normal_force.copy(),
        np.array([b.time,b.count,b.wall_work,b.contact_work,b.internal_work])]


class ConeGuards(unittest.TestCase):
    def unchanged(self,b,before):
        for actual,expected in zip(snapshot(b),before):
            np.testing.assert_array_equal(actual,expected)

    def test_force_balance_alone_cannot_accept_wrong_friction_law(self):
        b=ConeBlock(); b.commit(b.branch(.05,np.zeros(9,dtype=bool)))
        before=snapshot(b); c=b.branch(.1,np.zeros(9,dtype=bool))
        self.assertLessEqual(c['equilibrium_relative'],1e-8)
        self.assertGreater(float(np.max(np.linalg.norm(c['tangent_force'],axis=1)-.1*c['normal_force'])),1.)
        with self.assertRaisesRegex(CandidateFailure,'contact law/root'):
            b.commit(c)
        self.unchanged(b,before)

    def test_nonboolean_or_nonfinite_release_mask_is_not_silently_cast(self):
        b=ConeBlock(); before=snapshot(b)
        for mask in (np.full(9,np.nan),np.full(9,2),np.zeros((3,3),dtype=bool)):
            with self.subTest(mask=str(mask)):
                with self.assertRaisesRegex(ValueError,'released cone inventory'):
                    b.branch(.005,mask)
                self.unchanged(b,before)

    def test_corner_and_negative_iteration_guards_preserve_accepted_state(self):
        b=ConeBlock(); before=snapshot(b)
        with self.assertRaisesRegex(ValueError,'program corner'): b.advance(.075)
        with self.assertRaisesRegex(ValueError,'negative iteration budget'):
            b.branch(.005,np.zeros(9,dtype=bool),maximum_iterations=-1)
        self.unchanged(b,before)

    def test_full_contact_jacobian_includes_normal_capacity_coupling(self):
        # SPD manufactured stiffness; not a tangent generated by the tested code.
        K=np.array([[3.,.3,.4],[.3,2.,.1],[.4,.1,1.5]])
        u=np.array([-1.,.2,.5]); w=np.array([1.2,1.6]); mu=.5; kappa=1.7
        def independent_residual(x):
            f=K@x; C=-mu*f[0]; q=f[1:]-kappa*(x[1:]-w)
            self.assertGreater(np.linalg.norm(q),C)
            return C*q/np.linalg.norm(q)-f[1:]
        eps=1e-7
        reference=np.column_stack([-(independent_residual(u+eps*np.eye(3)[j])-
            independent_residual(u-eps*np.eye(3)[j]))/(2*eps) for j in range(3)])
        for angle in (0.,37.):
            a=np.deg2rad(angle); B=np.array([[np.cos(a),-np.sin(a)],[np.sin(a),np.cos(a)]])
            f=K@u
            response=cone_response(f[None,1:],np.array([-f[0]]),(u[1:]-w)[None,:],mu,kappa,B)
            matrix,_=cone_rows(K,np.zeros(3),np.array([0]),np.array([[1,2]]),response,mu,kappa,np.array([True]))
            np.testing.assert_allclose(matrix[1:],reference,atol=2e-8,rtol=0)
        # A frozen capacity is detectably wrong; this must not be a vacuous test.
        D=response['Pq'][0]
        wrong=(np.eye(2)-D)@K[1:]; wrong[:,1:]+=kappa*D
        self.assertGreater(float(np.linalg.norm(reference-wrong)),.1)

    def test_near_event_direction_uses_force_and_slip_uncertainty_not_division(self):
        # Literal failing endpoint from independent shared-DOF reversal, not
        # generated by the solver. Its normalized defect exceeds 1e-12 N,
        # although raw displacement-direction noise is only ~1e-16 m.
        c=dict(normal_force=np.array([2.]),
            tangent_force=np.array([[-.5999999999999999,-.8000000000000002]]),
            relative_increment=np.array([[4.499999979523661e-5,5.999999972683412e-5]]))
        limits=dict(force_tolerance_N=1e-12,slip_tolerance_m=1e-12)
        s=c['relative_increment']; old_defect=c['tangent_force']+s/np.linalg.norm(s)
        self.assertGreater(np.linalg.norm(old_defect),1e-12)
        self.assertTrue(feasible_cone(c,np.array([True]),.5,limits))
        # Genuine wrong direction and wrong disk magnitude must still fail.
        c['tangent_force']=np.array([[.6,.8]])
        self.assertFalse(feasible_cone(c,np.array([True]),.5,limits))
        c['tangent_force']=np.array([[-.8,.6]])
        self.assertFalse(feasible_cone(c,np.array([True]),.5,limits))
        c['tangent_force']=np.array([[-.8,-.8]])
        self.assertFalse(feasible_cone(c,np.array([True]),.5,limits))


if __name__=='__main__':unittest.main(verbosity=2)
