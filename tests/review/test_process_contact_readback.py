"""Read-only Q3 evidence checks; corrupted files exist only in temporary fixtures."""
import hashlib
import json
from pathlib import Path
import shutil
import sys
import tempfile
import unittest

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'scripts'))
from inspect_process_contact import inspect

BASE = ROOT/'outputs/process_contact_q3_20261001'


class ContactReadbackQ3(unittest.TestCase):
    def fixture(self, folder):
        target = Path(folder)/'Q3_CORRUPTION_FIXTURE_NOT_PHYSICAL'
        shutil.copytree(BASE/'j2_n3_i8', target)
        return target

    def rewrite_history_and_hash(self, target, change):
        path = target/'history.npz'
        with np.load(path, allow_pickle=False) as f:
            data = {key:f[key].copy() for key in f.files}
        change(data)
        np.savez_compressed(path, **data)
        report_path = target/'report.json'
        report = json.loads(report_path.read_text())
        report['artifact_sha256']['history.npz'] = hashlib.sha256(path.read_bytes()).hexdigest()
        report_path.write_text(json.dumps(report), encoding='utf-8')

    def test_01_three_actual_cases_have_complete_readback_and_independent_limits(self):
        for law, n in (('elastic', 8), ('j2', 8), ('j2', 16)):
            with self.subTest(law=law, increments_per_phase=n):
                result = inspect(BASE/f'{law}_n3_i{n}')
                self.assertEqual(result['status'], 'PASS_COMPLETE_READBACK')
                self.assertEqual(result['accepted_time_s'], .2)
                self.assertFalse(result['production_authorized'])
                self.assertLess(result['maximum_interval_gapwork_J'], 1e-6)
                self.assertLess(result['maximum_particle_plastic_defect_J'], 1e-10)
                if law == 'j2':
                    self.assertEqual(len(result['events']), 1)
                    self.assertAlmostEqual(result['events'][0]['physical_time_s'],
                                           .13214285714285715, delta=1e-8)
                    self.assertAlmostEqual(result['final_mean_cap_displacement_m'],
                                           -27.142857142857144e-6, delta=2e-10)
                    self.assertAlmostEqual(result['final_volume_mean_ep'],
                                           .002714285714285714, delta=1e-10)
                    self.assertAlmostEqual(result['final']['plastic_work_J'],
                                           .2442857142857143, delta=1e-7)
                    # Piecewise-uniaxial trapezoid references, not generated by contact.
                    reference_work = .2421428571428572 if n == 8 else .2440178571428572
                    self.assertAlmostEqual(result['independent_wall_work_J'], reference_work, delta=1e-7)
                else:
                    self.assertAlmostEqual(result['final_mean_cap_displacement_m'], 0., delta=1e-12)
                    self.assertEqual(result['final_volume_mean_ep'], 0.)
                    self.assertAlmostEqual(result['independent_wall_work_J'], 0., delta=1e-7)

    def test_02_artifact_tamper_rejected_before_readback(self):
        with tempfile.TemporaryDirectory(prefix='q3_readback_') as folder:
            target = self.fixture(folder)
            path = target/'final.vtk'
            path.write_bytes(path.read_bytes()+b'\nCORRUPTED_TEST_ONLY\n')
            with self.assertRaisesRegex(ValueError, 'artifact changed'):
                inspect(target)

    def test_03_rehashed_fake_contact_force_and_negative_gap_rejected(self):
        for field, message in (('normal_force_N', 'contact direction'),
                                ('gap_m', 'unilateral contact')):
            with self.subTest(field=field):
                with tempfile.TemporaryDirectory(prefix='q3_readback_') as folder:
                    target = self.fixture(folder)
                    def change(data):
                        if field == 'normal_force_N':
                            data[field][1, 0] += 100.
                        else:
                            data[field][1, 0] = -1e-8
                    self.rewrite_history_and_hash(target, change)
                    with self.assertRaisesRegex(ValueError, message):
                        inspect(target)

    def test_04_truncated_ledger_cannot_skip_contact_work(self):
        with tempfile.TemporaryDirectory(prefix='q3_readback_') as folder:
            target = self.fixture(folder); path = target/'report.json'
            report = json.loads(path.read_text()); report['records'] = report['records'][:1]
            path.write_text(json.dumps(report), encoding='utf-8')
            with self.assertRaisesRegex(ValueError, 'ledger/history time inventory'):
                inspect(target)

    def test_05_blocked_at_target_is_not_promoted_to_complete(self):
        with tempfile.TemporaryDirectory(prefix='q3_readback_') as folder:
            target = self.fixture(folder); path = target/'report.json'
            report = json.loads(path.read_text()); report['status'] = 'BLOCKED'
            path.write_text(json.dumps(report), encoding='utf-8')
            result = inspect(target)
            self.assertEqual(result['status'], 'PASS_PARTIAL_READBACK')
            self.assertEqual(result['completion_status'], 'BLOCKED')
            self.assertFalse(result['production_authorized'])

    def test_06_rehashed_ids_and_passive_labels_must_match_all_outputs(self):
        for field, message in (('particle_id', 'persistent contact identity'),
                                ('tracer_type', 'ID/label/accepted output')):
            with self.subTest(field=field):
                with tempfile.TemporaryDirectory(prefix='q3_readback_') as folder:
                    target = self.fixture(folder)
                    def change(data):
                        if field == 'particle_id':
                            data[field][1] = data[field][0]
                        else:
                            data[field][0] += 71
                    self.rewrite_history_and_hash(target, change)
                    with self.assertRaisesRegex(ValueError, message):
                        inspect(target)


if __name__ == '__main__':
    unittest.main(verbosity=2)
